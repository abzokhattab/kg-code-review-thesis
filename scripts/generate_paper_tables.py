def config_table() -> None:
    man = load("experiments/2026-07-05_injection_exp2/out/manifest.json")
    bands = Counter(i["band"] for i in man["injections"])
    struct = sum(v for k, v in bands.items() if k.startswith("S"))
    local = sum(v for k, v in bands.items() if k.startswith("L"))
    panel = load("results/checklist_evaluation_llm_multi__v2.json")["metadata"]["judges"]
    judges = ", ".join(j.split(":")[1] for j in panel)
    body = r"""\begin{table}[t]
\centering
\caption{Configuration of both experiments. Generation temperatures differ
because the two pipelines call different entry points; within an experiment
every arm shares one setting, so all contrasts are internally valid. No
generation seed is sent to the model, so Experiment 1's determinism rests on
$T=0$.}
\label{tab:config}
\footnotesize
\setlength{\tabcolsep}{3.5pt}
\begin{tabular}{lcc}
\toprule
& Experiment 1 & Experiment 2 \\
\midrule
Unit & merged PR & injected defect \\
""" + f"""$n$ & 40 & {struct + local} ({struct} struct., {local} control) \\\\
Repositories & 5 & 3 \\\\
Generator & gpt-4o & gpt-4o \\\\
Temperature & 0.0 & 0.3 \\\\
Diff cap (chars) & 50\\,000 & 12\\,000 \\\\
Judges & \\multicolumn{{2}}{{c}}{{{judges}}} \\\\
Aggregation & \\multicolumn{{2}}{{c}}{{majority of three, ties to 0}} \\\\
Outcome & rubric /25 & defect detected \\\\
Ground truth & LLM panel & static oracle \\\\
Statistics seed & \\multicolumn{{2}}{{c}}{{2026}} \\\\
""" + r"""\bottomrule
\end{tabular}
\end{table}"""
    write("config.tex",
          "results/checklist_evaluation_llm_multi__v2.json + injection manifest", body)


def main() -> None:
    exp1_means()
    exp1_deltas()
    exp1_builder()
    exp1_attribution()
    exp2_tables()
    config_table()
    print(f"\nall tables written to {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
