#!/usr/bin/env python3
"""generate_paper_tables.py — emit the conference paper's LaTeX tables.

Every table is generated from the raw result artefacts so that no number in
the paper is transcribed by hand. Output goes to the Overleaf working clone
(`paper/2026-08-12/draft/tables/`) as standalone `.tex` files that `main.tex`
pulls in with \\input.

Reads:
  results/BOOTSTRAP_STATS_v2.json                  Experiment 1 (era 2, n=40)
  results/BOOTSTRAP_STATS_joern.json               builder sensitivity (n=35)
  results/checklist_evaluation_llm_multi__v2.json  win attribution
  experiments/2026-07-05_injection_exp2/out/results.json    Experiment 2
  experiments/2026-07-05_injection_exp2/out/manifest.json   band composition

Writes:
  tables/exp1_means.tex          T1  per-mode means with bootstrap CIs
  tables/exp1_deltas.tex         T2  paired differences vs baseline
  tables/exp1_builder.tex        T3  grep vs Joern builder, original rubric
  tables/exp1_attribution.tex    T4  win concentration (placebo-band test)
  tables/exp2_structural.tex     T5  structural detection by arm
  tables/exp2_local.tex          T6  local-control placebo parity
  tables/config.tex              T7  generation and scoring configuration

Verified by paper/2026-08-12/verify_paper_numbers.py.
"""

from __future__ import annotations

import json
import os
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "paper", "2026-08-12", "draft", "tables")

MODE_LABEL = {
    "baseline": "baseline (diff only)",
    "kg": "kg",
    "rag": "rag",
    "hybrid": "hybrid (kg+rag)",
}
ARM_LABEL = {
    "baseline": "baseline (diff only)",
    "rag": "rag",
    "hybrid": "hybrid (kg+rag)",
    "kg": "kg (deployed CPG)",
    "kg_joern_inherit": "kg + inheritance edges",
    "kg_idealised": "kg idealised (ceiling)",
}
# Narrower variants for the single-column placebo table.
ARM_SHORT = {
    "baseline": "baseline",
    "rag": "rag",
    "hybrid": "hybrid",
    "kg": "kg",
    "kg_joern_inherit": "kg + inherit.",
    "kg_idealised": "kg idealised",
}
KG_RELEVANT = {"F3", "F4", "T1", "T2", "T3", "M1", "M3", "C2", "Q2"}

BANNER = ("% Generated by scripts/generate_paper_tables.py — do not edit by hand.\n"
          "% Source: {src}\n")


def load(rel: str):
    with open(os.path.join(ROOT, rel)) as fh:
        return json.load(fh)


def write(name: str, src: str, body: str) -> None:
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write(BANNER.format(src=src) + body.rstrip() + "\n")
    print(f"wrote tables/{name}")


def ci(d: dict, places: int = 2) -> str:
    return f"{d['mean']:.{places}f} [{d['ci_lo']:.{places}f}, {d['ci_hi']:.{places}f}]"


def stars(p: float) -> str:
    if p < 0.001:
        return r"\textsuperscript{***}"
    if p < 0.01:
        return r"\textsuperscript{**}"
    if p < 0.05:
        return r"\textsuperscript{*}"
    return ""


def fmt_p(p: float) -> str:
    if p < 0.0001:
        return r"$<$0.0001"
    if p >= 0.9995:
        return "1.00"
    return f"{p:.4f}".rstrip("0").rstrip(".")


# ------------------------------------------------------------------ T1, T2, T3
