def exp2_tables() -> None:
    src = "experiments/2026-07-05_injection_exp2/out/results.json"
    d = load(src)
    det, con = d["detection"], d["contrasts"]

    order = ("baseline", "rag", "hybrid", "kg", "kg_joern_inherit", "kg_idealised")
    rows = []
    for arm in order:
        s = det[f"structural:{arm}"]
        c = con.get(f"structural:{arm}-vs-baseline")
        delta = (f"{c['delta']:+.2f} [{c['ci95'][0]:+.2f}, {c['ci95'][1]:+.2f}] & "
                 f"{fmt_p(c['p_perm'])}{stars(c['p_perm'])}") if c else "--- & ---"
        bold = r"\textbf{" if arm == "kg" else ""
        end = "}" if arm == "kg" else ""
        rows.append(f"{bold}{ARM_LABEL[arm]}{end} & {s['detected']}/{s['n']} & "
                    f"{s['rate']:.2f} [{s['ci95'][0]:.2f}, {s['ci95'][1]:.2f}] & {delta} \\\\")

    body = r"""\begin{table*}[t]
\centering
\caption{Experiment 2, structural bands ($n=28$): detection of an injected
defect whose consequence lies outside the changed file. Rates with 95\%
bootstrap confidence intervals; contrasts by paired permutation test
($B=20\,000$, seed 2026). The diff-only baseline never detects one.}
\label{tab:exp2-structural}
\begin{tabular}{lcccc}
\toprule
Arm & Detected & Rate [95\% CI] & $\Delta$ vs baseline [95\% CI] & $p$ \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table*}"""
    write("exp2_structural.tex", src, body)

    rows = []
    for arm in order:
        s = det[f"local_control:{arm}"]
        c = con.get(f"local_control:{arm}-vs-baseline")
        delta = f"{c['delta']:+.2f} [{c['ci95'][0]:+.2f}, {c['ci95'][1]:+.2f}]" if c else "---"
        rows.append(f"{ARM_SHORT[arm]} & {s['detected']}/{s['n']} & {s['rate']:.2f} & {delta} \\\\")
    body = r"""\begin{table}[t]
\centering
\caption{Experiment 2, local-control bands ($n=12$): the placebo check. The
defect is visible inside the diff, so every arm should detect it and no arm
should gain from added context. All differences fall inside the
pre-registered parity window $[-0.15, +0.15]$.}
\label{tab:exp2-local}
\footnotesize
\setlength{\tabcolsep}{3.5pt}
\begin{tabular}{lccc}
\toprule
Arm & Det. & Rate & $\Delta$ vs base. [95\% CI] \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}"""
    write("exp2_local.tex", src, body)


