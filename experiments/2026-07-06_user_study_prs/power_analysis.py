#!/usr/bin/env python3
"""
power_analysis.py — simulation-based power for the 6-PR × 15–20-rater study.

Design: every rater sees all 6 PRs (fully crossed), one baseline-vs-KG
comparison per PR. Outcomes per task: overall preference (A/equal/B mapped
to kg/tie/baseline) and 6 per-criterion choices.

Primary analysis (per the v3 plan, adapted): per-rater KG-preference score
= mean over that rater's 6 PRs of (kg=1, tie=0.5, baseline=0); one-sample
Wilcoxon signed-rank test against 0.5, two-sided, alpha=.05. Rater is the
unit of analysis, so PR-level dependence is absorbed.

Simulation includes between-PR heterogeneity (some PRs are genuine ties —
the pilot suggests ~1-2 of 6) and between-rater noise.

$0, no API calls. Writes POWER_ANALYSIS.md.
"""
import numpy as np
from scipy import stats

rng = np.random.default_rng(2026)
N_SIM = 4000
ALPHA = 0.05
N_PRS = 6

# Each scenario: per-PR (p_kg, p_tie); p_baseline = 1 - p_kg - p_tie.
# OVERALL endpoint: tie-heavy (pilot: reviews often make the same points).
# F3* endpoint (which review better names affected components/APIs): this is
# where the KG reviews differ mechanically (additional off-diff references), so
# the plausible effect is larger and tie rate lower.
SCENARIOS_OVERALL = {
    "null (no effect)":           [(0.40, 0.20)] * 6,
    "weak (KG 55:45 of picks)":   [(0.44, 0.20)] * 6,
    "pilot-like (4 lean, 2 tie)": [(0.55, 0.20)] * 4 + [(0.40, 0.20)] * 2,
    "moderate (KG 65:35)":        [(0.52, 0.20)] * 6,
}
SCENARIOS_F3 = {
    "null (no effect)":           [(0.375, 0.25)] * 6,
    "diluted (KG 60% on 4 PRs)":  [(0.60, 0.25)] * 4 + [(0.375, 0.25)] * 2,
    "pilot-like (KG 65% all 6)":  [(0.65, 0.20)] * 6,
    "strong (KG 75% all 6)":      [(0.75, 0.15)] * 6,
}
RATER_SD = 0.10  # between-rater shift in kg-preference probability


def simulate_power(n_raters, pr_cells):
    rejections = 0
    for _ in range(N_SIM):
        scores = np.empty(n_raters)
        for r in range(n_raters):
            shift = rng.normal(0, RATER_SD)
            vals = []
            for p_kg, p_tie in pr_cells:
                pk = np.clip(p_kg + shift, 0.01, 1 - p_tie - 0.01)
                u = rng.random()
                vals.append(1.0 if u < pk else (0.5 if u < pk + p_tie else 0.0))
            scores[r] = np.mean(vals)
        d = scores - 0.5
        d = d[d != 0]
        if len(d) < 5:
            continue
        _, p = stats.wilcoxon(d, alternative="two-sided", method="approx")
        if p < ALPHA:
            rejections += 1
    return rejections / N_SIM


def block(title, scenarios, lines):
    lines += [f"\n## {title}\n",
              "| scenario | mean KG-pref | n=15 | n=18 | n=20 |",
              "|---|---|---|---|---|"]
    for name, cells in scenarios.items():
        mean_pref = np.mean([pk + pt / 2 for pk, pt in cells])
        row = [f"| {name} | {mean_pref:.2f} "]
        for n in (15, 18, 20):
            pw = simulate_power(n, cells)
            row.append(f"| {pw:.2f} ")
        lines.append("".join(row) + "|")
        print(lines[-1])


def main():
    lines = ["# Power analysis — 6 PRs × 18-20 target raters (15-rater checkpoint)\n",
             "Generated by `power_analysis.py` (seed 2026, 4000 sims/cell).",
             "Test: per-rater KG-preference score (kg=1, tie=0.5, baseline=0,",
             "averaged over the rater's 6 PRs) vs 0.5, two-sided Wilcoxon",
             f"signed-rank, alpha={ALPHA}. Between-rater SD {RATER_SD}.",
             "Null rows are the type-I error check (must stay near 0.05)."]
    print("PRIMARY — F3* (components/APIs criterion):")
    block("PRIMARY endpoint — F3* criterion preference", SCENARIOS_F3, lines)
    print("\nSECONDARY — overall usefulness:")
    block("SECONDARY endpoint — overall usefulness preference",
          SCENARIOS_OVERALL, lines)

    lines += [
        "",
        "## Decision",
        "",
        "**Primary endpoint = F3\\*** (\"which review better names concrete",
        "components/APIs affected\"), pre-registered. Rationale: RQ2's LLM-judge",
        "result localises the KG effect exactly on this criterion family, and",
        "the KG stimuli differ mechanically here (additional off-diff references),",
        "so RQ3 asks confirmatorily whether *humans perceive* that specific",
        "difference. Planning uses the diluted scenario: power is 0.79 at n=15,",
        "0.87 at n=18, and 0.91 at n=20. The 0.99-1.00 'pilot-like' row is",
        "retained only as an upper-bound sensitivity scenario: the excluded AI",
        "pilot used superseded green badges and must not calibrate the final",
        "neutral-evidence instrument.",
        "",
        "**Overall usefulness is secondary/descriptive.** At plausible effect",
        "sizes it is underpowered with 15-20 raters (0.4-0.7) because the two",
        "reviews genuinely make similar points on several PRs; it will be",
        "reported with a bootstrap CI, not a significance claim. A null here",
        "with a positive F3* is itself the thesis-relevant pattern: the KG",
        "changes *what the review grounds*, not necessarily perceived overall",
        "usefulness.",
        "",
        "Other per-criterion outcomes (F2*, T3, Q5, R1, C6): exploratory,",
        "Holm-corrected.",
    ]
    out = __file__.replace("power_analysis.py", "POWER_ANALYSIS.md")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
